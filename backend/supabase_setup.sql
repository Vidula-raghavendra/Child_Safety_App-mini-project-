-- 13. Live Locations Table (child pushes every 30s; one row per child via upsert)
CREATE TABLE IF NOT EXISTS public.live_locations (
  child_id UUID REFERENCES auth.users(id) NOT NULL PRIMARY KEY,
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.live_locations ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Children upsert own live location" ON public.live_locations;
DROP POLICY IF EXISTS "Parents read live locations of linked children" ON public.live_locations;

CREATE POLICY "Children upsert own live location" ON public.live_locations
  FOR ALL USING (auth.uid() = child_id)
  WITH CHECK (auth.uid() = child_id);

-- Parents can read live locations of children linked to them
CREATE POLICY "Parents read live locations of linked children" ON public.live_locations
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.family_links
      WHERE family_links.parent_id = auth.uid()
        AND family_links.child_id = live_locations.child_id
    )
  );

-- 14. Emergency Contacts Table (parents manage; children read)
CREATE TABLE IF NOT EXISTS public.emergency_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id UUID REFERENCES auth.users(id) NOT NULL,
  label TEXT NOT NULL,
  phone TEXT NOT NULL,
  icon_name TEXT DEFAULT 'person',
  display_order INT DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.emergency_contacts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Parents manage emergency contacts" ON public.emergency_contacts;
DROP POLICY IF EXISTS "Children read own emergency contacts" ON public.emergency_contacts;

-- Parents can manage contacts for their linked children
CREATE POLICY "Parents manage emergency contacts" ON public.emergency_contacts
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM public.family_links
      WHERE family_links.parent_id = auth.uid()
        AND family_links.child_id = emergency_contacts.child_id
    )
  );

CREATE POLICY "Children read own emergency contacts" ON public.emergency_contacts
  FOR SELECT USING (auth.uid() = child_id);

-- 15. Add parent_id to sos_alerts (needed for per-parent realtime filtering)
ALTER TABLE public.sos_alerts ADD COLUMN IF NOT EXISTS parent_id UUID REFERENCES auth.users(id);

