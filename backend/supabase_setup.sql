  FOR SELECT USING (auth.uid() = child_id);

-- 10. Zone Events Table (entered/exited/missing) — parent_id for fast per-parent queries
CREATE TABLE IF NOT EXISTS public.zone_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id BIGINT REFERENCES public.safe_zones(id) ON DELETE CASCADE,
  child_id UUID REFERENCES auth.users(id) NOT NULL,
  parent_id UUID REFERENCES auth.users(id),
  event_type TEXT CHECK (event_type IN ('entered', 'exited', 'missing')) NOT NULL,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.zone_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Children insert zone events" ON public.zone_events;
DROP POLICY IF EXISTS "Parents read zone events" ON public.zone_events;

